// Lịch sử clipboard kiểu Maccy.
// macOS không báo khi clipboard đổi nên buộc phải kiểm tra changeCount (một IPC rẻ). Để nhẹ:
// - 0,5 s khi người dùng đang thao tác, 2 s khi rảnh > 30 s, dừng hẳn khi màn hình ngủ;
// - timer có leeway để macOS gộp lần đánh thức CPU;
// - ảnh ghi ra file PNG, RAM chỉ giữ thumbnail lúc bảng đang mở;
// - ghi lịch sử xuống đĩa gộp 1,5 s một lần, trên hàng đợi nền.

struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id = UUID()
    var kind: Kind
    var text: String
    var rtf: Data?
    var image: String?
    var files: [String]?
    var app: String?
    var date: Date
    var pinned = false
    var hash: String
}

@MainActor @Observable
final class ClipboardModule: ZModule {
    static let id = "clipboard"
    static var name: String { L("Lịch sử clipboard", "Clipboard History") }
    static let replaces = "Maccy"
    static let symbol = "doc.on.clipboard"
    static var summary: String {
        L("Lưu những gì bạn sao chép, tìm và dán lại bằng ⌘⇧C. Bỏ qua mật khẩu từ trình quản lý mật khẩu.",
          "Keeps what you copy; search and paste it again with ⌘⇧C. Skips passwords from password managers.")
    }

    static let defaultShortcut = KeyCombo(kVK_ANSI_C, KeyCombo.cmd | KeyCombo.shift)
    /// Kiểu dữ liệu đánh dấu "đừng lưu" (chuẩn nspasteboard.org + vài app quản lý mật khẩu).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]
    static let defaultIgnoredApps = ["com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password",
                                     "com.agilebits.onepassword7", "com.bitwarden.desktop"]

    private(set) var items: [ClipItem] = []
    var query = ""
    var selected = 0

    var maxItems = Pref.int("clipboard.max", 200) { didSet { Pref.set("clipboard.max", maxItems); trim(); scheduleSave() } }
    var autoPaste = Pref.bool("clipboard.autoPaste", true) { didSet { Pref.set("clipboard.autoPaste", autoPaste) } }
    var ignoredApps: [String] = (UserDefaults.standard.stringArray(forKey: "clipboard.ignoredApps") ?? ClipboardModule.defaultIgnoredApps) {
        didSet { Pref.set("clipboard.ignoredApps", ignoredApps) }
    }

    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: DispatchSourceTimer?
    @ObservationIgnored private var interval: Double = 0
    @ObservationIgnored private var observers: [NSObjectProtocol] = []
    @ObservationIgnored private var hotkey: UInt32?
    @ObservationIgnored private var panel: ClipboardPanel?
    @ObservationIgnored private var keyMonitor: Any?
    @ObservationIgnored private var saveWork: DispatchWorkItem?
    @ObservationIgnored var thumbnails: [UUID: NSImage] = [:]
    @ObservationIgnored private let io = DispatchQueue(label: "zmac.clipboard.io", qos: .utility)

    nonisolated static let dir: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("zMac/Clipboard", isDirectory: true)
    }()
    nonisolated static var imagesDir: URL { dir.appendingPathComponent("images", isDirectory: true) }
    nonisolated static var historyFile: URL { dir.appendingPathComponent("history.json") }

    init() {}

    func start() {
        try? FileManager.default.createDirectory(at: Self.imagesDir, withIntermediateDirectories: true)
        load()
        lastChange = NSPasteboard.general.changeCount
        registerHotkey()
        let ws = NSWorkspace.shared.notificationCenter
        observers.append(ws.addObserver(forName: NSWorkspace.screensDidSleepNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.pause() }
        })
        observers.append(ws.addObserver(forName: NSWorkspace.screensDidWakeNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.schedule(0.5) }
        })
        // Chép xong thường chuyển app: kiểm tra ngay để không lỡ.
        observers.append(ws.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        })
        schedule(0.5)
    }

    func stop() {
        pause()
        observers.forEach { NSWorkspace.shared.notificationCenter.removeObserver($0) }
        observers = []
        HotKeyCenter.shared.unregister(hotkey)
        hotkey = nil
        hidePanel()
        panel = nil
        saveNow()
    }

    private func registerHotkey() {
        HotKeyCenter.shared.unregister(hotkey)
        hotkey = Shortcuts.combo("clipboard.open", Self.defaultShortcut).map {
            HotKeyCenter.shared.register($0) { [weak self] in self?.togglePanel() }
        }
    }

    // MARK: Theo dõi clipboard

    private func schedule(_ secs: Double) {
        guard secs != interval || timer == nil else { return }
        interval = secs
        timer?.cancel()
        let t = DispatchSource.makeTimerSource(queue: .main)
        t.schedule(deadline: .now() + secs, repeating: secs, leeway: .milliseconds(Int(secs * 500)))
        t.setEventHandler { [weak self] in MainActor.assumeIsolated { self?.tick() } }
        t.resume()
        timer = t
    }

    private func pause() {
        timer?.cancel()
        timer = nil
    }

    private func tick() {
        check()
        let anyInput = CGEventType(rawValue: ~0) ?? .mouseMoved
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: anyInput)
        schedule(idle > 30 ? 2.0 : 0.5)
    }

    func check() {
        let pb = NSPasteboard.general
        let cc = pb.changeCount
        guard cc != lastChange else { return }
        lastChange = cc
        guard let types = pb.types, !types.isEmpty else { return }
        if !Set(types.map(\.rawValue)).isDisjoint(with: Self.ignoredTypes) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, ignoredApps.contains(source) { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            add(ClipItem(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: ", "), files: paths,
                         app: source, date: Date(), hash: Self.sha(paths.joined(separator: "\n"))))
            return
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let text = s.count > 200_000 ? String(s.prefix(200_000)) : s
            var rtf = pb.data(forType: .rtf)
            if (rtf?.count ?? 0) > 256_000 { rtf = nil }
            add(ClipItem(kind: .text, text: text, rtf: rtf, app: source, date: Date(), hash: Self.sha(text)))
            return
        }
        if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count < 40_000_000 {
            let png = pb.data(forType: .png) ?? NSBitmapImageRep(data: raw)?.representation(using: .png, properties: [:])
            guard let png else { return }
            let hash = Self.sha(png)
            if let i = items.firstIndex(where: { $0.hash == hash }) { bump(i); return }
            let id = UUID()
            let name = id.uuidString + ".png"
            let url = Self.imagesDir.appendingPathComponent(name)
            io.async { try? png.write(to: url) }
            let size = NSBitmapImageRep(data: png).map { "\($0.pixelsWide)×\($0.pixelsHigh)" } ?? ""
            add(ClipItem(id: id, kind: .image, text: L("Ảnh ", "Image ") + size, image: name, app: source, date: Date(), hash: hash))
        }
    }

    private func add(_ item: ClipItem) {
        if let i = items.firstIndex(where: { $0.hash == item.hash }) { bump(i); return }
        items.insert(item, at: 0)
        trim()
        scheduleSave()
    }

    private func bump(_ i: Int) {
        var it = items.remove(at: i)
        it.date = Date()
        items.insert(it, at: 0)
        scheduleSave()
    }

    private func trim() {
        var kept = 0
        var removed: [ClipItem] = []
        items.removeAll { it in
            if it.pinned { return false }
            kept += 1
            if kept > maxItems { removed.append(it); return true }
            return false
        }
        deleteFiles(removed)
    }

    private func deleteFiles(_ list: [ClipItem]) {
        let names = list.compactMap(\.image)
        guard !names.isEmpty else { return }
        io.async { names.forEach { try? FileManager.default.removeItem(at: Self.imagesDir.appendingPathComponent($0)) } }
    }

    static func sha(_ s: String) -> String { sha(Data(s.utf8)) }
    static func sha(_ d: Data) -> String { SHA256.hash(data: d).prefix(16).map { String(format: "%02x", $0) }.joined() }

    // MARK: Lưu trữ

    private func load() {
        guard let data = try? Data(contentsOf: Self.historyFile) else { return }
        let dec = JSONDecoder()
        dec.dateDecodingStrategy = .iso8601
        items = (try? dec.decode([ClipItem].self, from: data)) ?? []
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let w = DispatchWorkItem { [weak self] in MainActor.assumeIsolated { self?.saveNow() } }
        saveWork = w
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5, execute: w)
    }

    private func saveNow() {
        saveWork?.cancel()
        saveWork = nil
        let snapshot = items
        io.async {
            let enc = JSONEncoder()
            enc.dateEncodingStrategy = .iso8601
            if let data = try? enc.encode(snapshot) { try? data.write(to: Self.historyFile, options: .atomic) }
        }
    }

    // MARK: Thao tác

    var filtered: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let base = q.isEmpty ? items : items.filter { $0.text.localizedCaseInsensitiveContains(q) }
        return base.filter(\.pinned) + base.filter { !$0.pinned }
    }

    func copyToPasteboard(_ item: ClipItem, plain: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text, forType: .string)
            if !plain, let rtf = item.rtf { pb.setData(rtf, forType: .rtf) }
        case .files:
            pb.writeObjects((item.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let name = item.image, let img = NSImage(contentsOf: Self.imagesDir.appendingPathComponent(name)) {
                pb.writeObjects([img])
            }
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }) { bump(i) }
    }

    func paste(_ item: ClipItem, plain: Bool = false) {
        hidePanel()
        copyToPasteboard(item, plain: plain)
        guard autoPaste, AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.06) { Self.postCmdV() }
    }

    static func postCmdV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgAnnotatedSessionEventTap)
        up?.post(tap: .cgAnnotatedSessionEventTap)
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        trim()
        scheduleSave()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles([item])
        thumbnails[item.id] = nil
        selected = min(selected, max(filtered.count - 1, 0))
        scheduleSave()
    }

    func clearUnpinned() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        deleteFiles(removed)
        scheduleSave()
    }

    func thumbnail(_ item: ClipItem) -> NSImage? {
        guard item.kind == .image, let name = item.image else { return nil }
        if let t = thumbnails[item.id] { return t }
        let url = Self.imagesDir.appendingPathComponent(name)
        let opts: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                     kCGImageSourceThumbnailMaxPixelSize: 96, kCGImageSourceCreateThumbnailWithTransform: true]
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        let img = NSImage(cgImage: cg, size: .zero)
        thumbnails[item.id] = img
        return img
    }

    // MARK: Bảng

    func togglePanel() {
        if panel?.isVisible == true { hidePanel() } else { showPanel() }
    }

    private func showPanel() {
        check()
        query = ""
        selected = 0
        let p = panel ?? ClipboardPanel()
        panel = p
        p.onResign = { [weak self] in self?.hidePanel() }
        p.contentView = NSHostingView(rootView: ClipboardView(model: self))
        let size = NSSize(width: 420, height: 480)
        let mouse = NSEvent.mouseLocation
        let vf = (NSScreen.screens.first { $0.frame.contains(mouse) } ?? NSScreen.main)?.visibleFrame ?? .zero
        let x = min(max(mouse.x, vf.minX + 8), vf.maxX - size.width - 8)
        let y = min(max(mouse.y - size.height, vf.minY + 8), vf.maxY - size.height - 8)
        p.setFrame(NSRect(origin: NSPoint(x: x, y: y), size: size), display: true)
        p.makeKeyAndOrderFront(nil)
        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] e in
            MainActor.assumeIsolated { self?.handleKey(e) ?? true } ? e : nil
        }
    }

    func hidePanel() {
        if let keyMonitor { NSEvent.removeMonitor(keyMonitor) }
        keyMonitor = nil
        panel?.onResign = nil
        panel?.orderOut(nil)
        // Huỷ cây view và thumbnail: bảng ẩn không giữ RAM.
        panel?.contentView = nil
        thumbnails = [:]
    }

    /// true = để sự kiện đi tiếp (vào ô tìm kiếm).
    private func handleKey(_ e: NSEvent) -> Bool {
        let list = filtered
        let mods = e.modifierFlags.intersection(.deviceIndependentFlagsMask)
        switch Int(e.keyCode) {
        case kVK_Escape: hidePanel(); return false
        case kVK_DownArrow: selected = min(selected + 1, max(list.count - 1, 0)); return false
        case kVK_UpArrow: selected = max(selected - 1, 0); return false
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if list.indices.contains(selected) { paste(list[selected], plain: mods.contains(.option)) }
            return false
        default: break
        }
        if mods.contains(.command), let n = Int(e.charactersIgnoringModifiers ?? ""), (1...9).contains(n) {
            if list.indices.contains(n - 1) { paste(list[n - 1]) }
            return false
        }
        if mods.contains(.option), list.indices.contains(selected) {
            if Int(e.keyCode) == kVK_ANSI_P { togglePin(list[selected]); return false }
            if Int(e.keyCode) == kVK_Delete { delete(list[selected]); return false }
        }
        return true
    }

    // MARK: Cài đặt

    func settingsView() -> AnyView {
        moduleForm {
            Section(L("Chung", "General")) {
                HStack {
                    Text(L("Mở lịch sử", "Open history"))
                    Spacer()
                    ShortcutField(id: "clipboard.open", defaultCombo: Self.defaultShortcut) { [weak self] in self?.registerHotkey() }
                }
                Picker(L("Giữ tối đa", "Keep up to"), selection: Binding(get: { self.maxItems }, set: { self.maxItems = $0 })) {
                    ForEach([50, 100, 200, 500, 1000], id: \.self) { Text("\($0)").tag($0) }
                }
                Toggle(L("Dán luôn sau khi chọn", "Paste right after choosing"),
                       isOn: Binding(get: { self.autoPaste }, set: { self.autoPaste = $0 }))
                if autoPaste && !Permissions.shared.accessibility {
                    PermissionRow(title: L("Cần quyền Trợ năng để dán", "Accessibility needed to paste"),
                                  detail: L("Không có quyền thì chỉ chép vào clipboard.", "Without it items are only copied."),
                                  granted: false) { Permissions.shared.requestAccessibility() }
                }
                Text(L("Trong bảng: ↑ ↓ chọn, ↩ dán, ⌥↩ dán không định dạng, ⌘1 đến ⌘9 dán nhanh, ⌥P ghim, ⌥⌫ xoá.",
                       "In the panel: ↑ ↓ to pick, ↩ paste, ⌥↩ paste as plain text, ⌘1 to ⌘9 quick paste, ⌥P pin, ⌥⌫ delete."))
                    .font(.caption).foregroundStyle(.secondary)
            }
            Section(L("Bỏ qua app", "Ignored apps")) {
                ForEach(ignoredApps, id: \.self) { id in
                    HStack {
                        Text(Self.appName(id)).lineLimit(1)
                        Text(id).font(.caption).foregroundStyle(.secondary).lineLimit(1)
                        Spacer()
                        Button { self.ignoredApps.removeAll { $0 == id } } label: { Image(systemName: "minus.circle") }
                            .buttonStyle(.borderless)
                    }
                }
                Button(L("Thêm app…", "Add app…")) { self.pickIgnoredApp() }
                Text(L("Mật khẩu từ app quản lý mật khẩu luôn được bỏ qua.", "Passwords from password managers are always skipped."))
                    .font(.caption).foregroundStyle(.secondary)
            }
            Section(L("Dữ liệu", "Data")) {
                LabeledContent(L("Đang lưu", "Stored"), value: "\(items.count)")
                Button(L("Xoá mục chưa ghim", "Clear unpinned items"), role: .destructive) { self.clearUnpinned() }
            }
        }
    }

    func quickView() -> AnyView? {
        AnyView(VStack(alignment: .leading, spacing: 4) {
            ForEach(items.prefix(5)) { it in
                Button { self.copyToPasteboard(it) } label: {
                    HStack {
                        Image(systemName: it.kind == .image ? "photo" : it.kind == .files ? "doc" : "text.alignleft")
                            .foregroundStyle(.secondary).frame(width: 16)
                        Text(it.text.replacingOccurrences(of: "\n", with: " ")).lineLimit(1)
                        Spacer()
                    }
                    .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
            }
            if items.isEmpty { Text(L("Chưa có gì.", "Nothing yet.")).foregroundStyle(.secondary) }
        }.font(.callout))
    }

    static func appName(_ bundleID: String) -> String {
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return bundleID }
        return FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
    }

    private func pickIgnoredApp() {
        let p = NSOpenPanel()
        p.allowedContentTypes = [.application]
        p.directoryURL = URL(fileURLWithPath: "/Applications")
        p.allowsMultipleSelection = true
        guard p.runModal() == .OK else { return }
        for url in p.urls {
            if let id = Bundle(url: url)?.bundleIdentifier, !ignoredApps.contains(id) { ignoredApps.append(id) }
        }
    }
}

// MARK: - Panel nhận phím mà không kích hoạt app (app đang dùng vẫn active để dán vào)

final class ClipboardPanel: NSPanel {
    var onResign: (() -> Void)?

    init() {
        super.init(contentRect: .zero, styleMask: [.titled, .fullSizeContentView, .nonactivatingPanel],
                   backing: .buffered, defer: true)
        titleVisibility = .hidden
        titlebarAppearsTransparent = true
        standardWindowButton(.closeButton)?.isHidden = true
        standardWindowButton(.miniaturizeButton)?.isHidden = true
        standardWindowButton(.zoomButton)?.isHidden = true
        isMovableByWindowBackground = true
        level = .popUpMenu
        collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient, .ignoresCycle]
        hidesOnDeactivate = false
        isReleasedWhenClosed = false
    }

    override var canBecomeKey: Bool { true }
    override func resignKey() {
        super.resignKey()
        let f = onResign
        DispatchQueue.main.async { f?() }
    }
}

struct ClipboardView: View {
    @Bindable var model: ClipboardModule
    @FocusState private var searchFocused: Bool

    var body: some View {
        let list = model.filtered
        VStack(spacing: 0) {
            HStack(spacing: 8) {
                Image(systemName: "magnifyingglass").foregroundStyle(.white.opacity(0.55))
                TextField(L("Tìm trong lịch sử", "Search history"), text: $model.query)
                    .textFieldStyle(.plain)
                    .font(.system(size: 14))
                    .focused($searchFocused)
                    .onChange(of: model.query) { _, _ in model.selected = 0 }
            }
            .padding(.horizontal, 12).padding(.vertical, 9)
            .background(RoundedRectangle(cornerRadius: 11, style: .continuous).fill(.white.opacity(0.08)))
            .overlay(RoundedRectangle(cornerRadius: 11, style: .continuous)
                .strokeBorder(searchFocused ? ZTheme.purple.light.opacity(0.7) : .white.opacity(0.08), lineWidth: 1))
            .padding(10)
            ScrollViewReader { proxy in
                ScrollView {
                    LazyVStack(spacing: 2) {
                        ForEach(Array(list.enumerated()), id: \.element.id) { i, item in
                            ClipRow(item: item, index: i, selected: i == model.selected, thumb: model.thumbnail(item))
                                .id(item.id)
                                .contentShape(Rectangle())
                                .onTapGesture { model.paste(item) }
                                .onHover { if $0 { model.selected = i } }
                                .contextMenu {
                                    Button(item.pinned ? L("Bỏ ghim", "Unpin") : L("Ghim", "Pin")) { model.togglePin(item) }
                                    Button(L("Dán không định dạng", "Paste as plain text")) { model.paste(item, plain: true) }
                                    Button(L("Xoá", "Delete"), role: .destructive) { model.delete(item) }
                                }
                        }
                    }
                    .padding(6)
                }
                .onChange(of: model.selected) { _, s in
                    if list.indices.contains(s) { proxy.scrollTo(list[s].id) }
                }
            }
            if list.isEmpty {
                Text(model.items.isEmpty ? L("Chưa có gì. Hãy sao chép thứ gì đó.", "Nothing yet. Copy something.")
                     : L("Không tìm thấy.", "No matches."))
                    .foregroundStyle(.secondary).frame(maxHeight: .infinity)
            }
        }
        .background {
            ZStack {
                VisualEffectBlur(material: .hudWindow)
                LinearGradient(colors: [ZTheme.navyTop.opacity(0.72), ZTheme.navyBottom.opacity(0.86)],
                               startPoint: .top, endPoint: .bottom)
            }
        }
        .environment(\.colorScheme, .dark)
        .onAppear { searchFocused = true }
    }
}

struct ClipRow: View {
    let item: ClipItem
    let index: Int
    let selected: Bool
    let thumb: NSImage?

    var body: some View {
        HStack(spacing: 10) {
            if let thumb {
                Image(nsImage: thumb).resizable().aspectRatio(contentMode: .fill).frame(width: 30, height: 30)
                    .clipShape(RoundedRectangle(cornerRadius: 8, style: .continuous))
            } else {
                ZTile(symbol: symbol, hue: hue, size: 28)
            }
            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ "))
                .font(.system(size: 13))
                .lineLimit(2).truncationMode(.tail)
                .frame(maxWidth: .infinity, alignment: .leading)
            if item.pinned { Image(systemName: "pin.fill").font(.system(size: 11)).foregroundStyle(ZTheme.orange.light) }
            if index < 9 {
                Text("⌘\(index + 1)")
                    .font(.system(size: 11, weight: .medium).monospacedDigit())
                    .foregroundStyle(.white.opacity(0.5))
                    .padding(.horizontal, 6).padding(.vertical, 2)
                    .background(Capsule().fill(.white.opacity(0.07)))
            }
        }
        .padding(.horizontal, 8).padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 10, style: .continuous)
            .fill(selected ? AnyShapeStyle(ZTheme.purple.gradient.opacity(0.3)) : AnyShapeStyle(Color.clear)))
        .overlay(RoundedRectangle(cornerRadius: 10, style: .continuous)
            .strokeBorder(selected ? ZTheme.purple.light.opacity(0.6) : .clear, lineWidth: 1))
    }

    private var isLink: Bool {
        item.kind == .text && (item.text.hasPrefix("http://") || item.text.hasPrefix("https://"))
    }
    private var symbol: String {
        switch item.kind {
        case .files: "doc.fill"
        case .image: "photo"
        case .text: isLink ? "link" : "text.alignleft"
        }
    }
    private var hue: ZTheme.Hue {
        switch item.kind {
        case .files: ZTheme.orange
        case .image: ZTheme.green
        case .text: isLink ? ZTheme.blue : ZTheme.slate
        }
    }
}

